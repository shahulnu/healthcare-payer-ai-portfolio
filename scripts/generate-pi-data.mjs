// Generates the synthetic provider cohort for Payment Integrity Radar.
//
//   node scripts/generate-pi-data.mjs
//
// Writes data/pi/providers.json (what the detector sees) and evals/pi-labels.json (which
// providers had patterns injected, kept apart so the detector can't read them). A seeded
// generator makes the output repeatable. Every provider is invented; nothing here describes
// a real clinician or claim.

import { mkdirSync, writeFileSync } from "node:fs";

function mulberry32(seed) {
  return () => {
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const rand = mulberry32(20261107);
const uniform = (a, b) => a + (b - a) * rand();
const normal = (mean, sd) => {
  const u = Math.max(rand(), 1e-9);
  return mean + sd * Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * rand());
};
const clamp = (x, a, b) => Math.min(b, Math.max(a, x));
const round = (x, d) => Number(x.toFixed(d));

function familyMedicine(id) {
  const encounters = Math.round(uniform(900, 2600));
  const risk = clamp(normal(1.05, 0.14), 0.7, 1.45);
  const level5 = clamp(0.01 + 0.045 * risk + normal(0, 0.009), 0.005, 0.2);
  const level4 = clamp(normal(0.38, 0.035), 0.25, 0.5);
  return {
    id,
    specialty: "Family Medicine",
    encounters,
    patientRiskScore: round(risk, 2),
    level5Share: round(level5, 3),
    level4Share: round(level4, 3),
    modifier25Rate: round(clamp(normal(0.08, 0.016), 0.02, 0.16), 3),
    peakDayHours: round(clamp(normal(8.4, 0.9), 5.5, 11.5), 1),
    allowedPerPatient: Math.round(clamp(normal(410, 42), 280, 540)),
  };
}

function physicalTherapy(id) {
  const visits = Math.round(uniform(1400, 4200));
  const perPatient = clamp(normal(12, 1.5), 8, 16);
  return {
    id,
    specialty: "Physical Therapy",
    encounters: visits,
    patients: Math.round(visits / perPatient),
    unitsPerVisit: round(clamp(normal(3.1, 0.18), 2.5, 3.7), 2),
    fourPlusUnitShare: round(clamp(normal(0.18, 0.035), 0.08, 0.3), 3),
    visitsPerPatient: round(perPatient, 1),
    modifier59Rate: round(clamp(normal(0.12, 0.025), 0.04, 0.2), 3),
    peakDayHours: round(clamp(normal(8.9, 0.8), 6, 11.5), 1),
  };
}

const providers = [];
for (let i = 1; i <= 80; i++) providers.push(familyMedicine(`PRV-SYN-${1000 + i}`));
for (let i = 1; i <= 40; i++) providers.push(physicalTherapy(`PRV-SYN-${2000 + i}`));

// Patterns injected on top of the normal cohort.
const inject = [
  { id: "PRV-SYN-1017", pattern: "level5_share", tier: "high", set: { level5Share: 0.48, level4Share: 0.31, patientRiskScore: 1.02 } },
  { id: "PRV-SYN-1042", pattern: "level5_share", tier: "medium", set: { level5Share: 0.125, patientRiskScore: 0.98 } },
  { id: "PRV-SYN-1031", pattern: "modifier25_rate", tier: "high", set: { modifier25Rate: 0.41 } },
  { id: "PRV-SYN-1058", pattern: "peak_day_hours", tier: "high", set: { peakDayHours: 19.5, encounters: 2580 } },
  { id: "PRV-SYN-2009", pattern: "units_per_visit", tier: "high", set: { unitsPerVisit: 5.4, fourPlusUnitShare: 0.78 } },
  { id: "PRV-SYN-2027", pattern: "visits_per_patient", tier: "high", set: { visitsPerPatient: 31.0, patients: 96, encounters: 2976 } },
];
for (const x of inject) Object.assign(providers.find((p) => p.id === x.id), x.set);

// A decoy: level-5 share looks high against peers, but the panel is much sicker, so risk
// adjustment should clear it. A detector that ignores case mix gets this one wrong.
const decoyId = "PRV-SYN-1066";
Object.assign(providers.find((p) => p.id === decoyId), { patientRiskScore: 2.1, level5Share: 0.109 });

mkdirSync("data/pi", { recursive: true });
writeFileSync(
  "data/pi/providers.json",
  JSON.stringify({ period: "2026 Q3", note: "Synthetic providers generated by scripts/generate-pi-data.mjs. Not real clinicians.", providers }, null, 2) + "\n",
);
writeFileSync(
  "evals/pi-labels.json",
  JSON.stringify(
    {
      note: "Injected patterns from scripts/generate-pi-data.mjs. The detector never reads this file. Real payment-integrity labels would come from closed SIU cases.",
      injected: Object.fromEntries(inject.map((x) => [x.id, { pattern: x.pattern, tier: x.tier }])),
      decoys: [decoyId],
    },
    null,
    2,
  ) + "\n",
);
console.log(`Wrote ${providers.length} providers, ${inject.length} injected patterns, 1 decoy.`);
